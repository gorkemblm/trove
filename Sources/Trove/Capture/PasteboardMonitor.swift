import AppKit
import OSLog

/// Polls the general pasteboard. macOS has no change notification, so a 0.5 s timer
/// compares `changeCount`. One integer comparison per tick keeps idle CPU near zero.
@MainActor
final class PasteboardMonitor {
    /// Markers that password managers and other tools set on content that must not be stored.
    /// See nspasteboard.org.
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]
    /// Chromium browsers (Chrome, Arc, Edge, Brave) add the page URL to copied content.
    static let chromiumSourceURL = NSPasteboard.PasteboardType("org.chromium.source-url")

    var onCapture: ((CapturedContent, ClipSource) -> Void)?
    var isExcluded: ((String?) -> Bool)?
    var recordSourceURL: () -> Bool = { true }
    var maxImageBytes: () -> Int = { 20 * 1_048_576 }

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount
    /// Every app that was in front since the last tick. A copy in an ignored app, followed by a
    /// fast ⌘Tab, is seen only at the next tick, when another app is in front: it is skipped too.
    private var appsSinceLastTick: [String?] = []
    private var activationObserver: NSObjectProtocol?
    private let log = Logger(subsystem: AppInfo.bundleID, category: "monitor")

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        appsSinceLastTick = [NSWorkspace.shared.frontmostApplication?.bundleIdentifier]
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            let bundleID = app?.bundleIdentifier
            MainActor.assumeIsolated { self?.appsSinceLastTick.append(bundleID) }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        if let activationObserver { NSWorkspace.shared.notificationCenter.removeObserver(activationObserver) }
        activationObserver = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        let recentApps = appsSinceLastTick
        appsSinceLastTick = [NSWorkspace.shared.frontmostApplication?.bundleIdentifier]
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        let types = Set(pasteboard.types ?? [])
        if types.contains(Copier.ownType) { return }
        if !types.isDisjoint(with: Self.ignoredTypes) {
            log.info("Skipped content marked concealed or transient")
            return
        }
        let app = NSWorkspace.shared.frontmostApplication
        if isExcluded?(app?.bundleIdentifier) == true || recentApps.contains(where: { isExcluded?($0) == true }) {
            log.info("Skipped content from an ignored app")
            return
        }
        guard let content = ClipClassifier.capture(from: pasteboard, maxImageBytes: maxImageBytes()) else { return }
        let url = recordSourceURL() ? pasteboard.string(forType: Self.chromiumSourceURL) : nil
        onCapture?(content, ClipSource(bundleID: app?.bundleIdentifier, appName: app?.localizedName, url: url))
    }
}
